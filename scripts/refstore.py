def cmd_submit(a) -> None:
    root = store_root()
    jobs = root / "jobs"
    jobs.mkdir(parents=True, exist_ok=True)
    rows = load_index()

    if a.what == "mlip":
        todo = [r for r in rows if r["mlip_state"] in ("todo", "partial")]
        script = Path(__file__).with_name("refstore_mlip.sbatch")
    else:
        # Deliberately NOT gated on the MLIP.  The MLIP only supplies a better
        # starting geometry; MP's own relaxed cell is a valid seed on its own,
        # and gating on it would park 2,869 structures behind a GPU queue.
        #
        # The test is `ready`, NOT `static_state != done`.  A structure whose
        # relax was killed mid-run but whose static then ran anyway looks
        # finished and is not: that static energy sits on an unrelaxed cell.
        # One such row (mp-1181327-Fe3B) was already in the store.
        todo = [r for r in rows if r["ready"] != "True"]
        script = Path(__file__).with_name("refstore_dft.sbatch")

    # Structures the store has decided not to wait for.  IGNORED, not failed:
    # they compute fine, they just sit too far above the hull to change it.
    # Listed in <store>/ignored.json so the decision is reviewable -- delete an
    # entry there and the structure comes straight back into the queue.
    ignored = load_ignored()
    if ignored and a.what == "dft":
        before = len(todo)
        todo = [r for r in todo if r["mp_id"] not in ignored]
        if before != len(todo):
            print(f"skipping {before - len(todo)} structure(s) in ignored.json "
                  f"-- too far above the hull to matter (not failures)")

    # Never hand a folder to a second job while the first still holds it: two
    # VASP processes writing one directory is corruption, not a race.
    in_flight = folders_in_flight(root)
    if in_flight:
        before = len(todo)
        todo = [r for r in todo if r["folder"] not in in_flight]
        if before != len(todo):
            print(f"skipping {before - len(todo)} structure(s) already handed to "
                  f"a job that is still queued or running")

    if a.chemsys:
        want = set(a.chemsys.split("-"))
        todo = [r for r in todo if r["chemsys"]
                and set(r["chemsys"].split("-")) <= want]
        print(f"restricted to {a.chemsys} (and its sub-systems)")
    if a.limit:
        todo = todo[: a.limit]
    if not todo:
        print(f"nothing to do for {a.what}")
        return

    # Stamped, because a running array reads its task file line by line for as
    # long as it lives.  A second submission reusing the name would rewrite the
    # list under a job already using it, and every task not yet started would
    # run the wrong structure.
    tag = (a.chemsys or "all").replace("-", "")
    tasks = jobs / f"{a.what}-{tag}-{time.strftime('%m%d-%H%M')}.tasks"
    if a.apply:
        # Only on --apply: a dry run that rewrote this would silently change the
        # task list a running array is reading line by line.
        tasks.write_text("".join(f"{structures_dir() / r['folder']}\n"
                                 for r in todo))
    print(f"{len(todo)} task(s) -> {tasks}"
          f"{'' if a.apply else '  (not written -- dry run)'}")

    if a.what == "dft" and a.apply:
        # Wipe every stage that is about to be redone.  This is also what makes
        # `refcheck.py` honest: without it, a structure queued for a rerun keeps
        # reporting its OLD failure until the new attempt overwrites the file.
        #
        # RE-READ EACH FOLDER FIRST.  index.csv is a snapshot, and jobs finish
        # while you are looking at it.  Cleaning straight from the index deleted
        # 168 completed statics and 76 converged relaxes here on 2026-09-09 --
        # work that a running array had produced in the 38 minutes between the
        # index being built and the submit being typed.  Nothing was lost for
        # good, because everything wiped was resubmitted, but the CPU was.
        cleaned = skipped = 0
        keep = []
        for r in todo:
            folder = structures_dir() / r["folder"]
            fresh = scan_one(folder)
            if fresh["ready"] is True:
                skipped += 1
                continue                       # finished since the index was built
            keep.append(r)
            if fresh["relax_converged"] is not True:
                clean_stage(folder / "dft_relax", carry_contcar=True)
                cleaned += 1
            # A relax that has to be redone invalidates its own static: that
            # energy sits on a cell that is about to change.  But if the relax
            # stands, a finished static must not be touched.
            if fresh["relax_converged"] is not True or fresh["static_state"] != "done":
                clean_stage(folder / "dft_static", carry_contcar=False)
                cleaned += 1
        if skipped:
            print(f"skipped {skipped} structure(s) that finished after the index "
                  f"was built -- rerun `index` to see them")
            todo = keep
            tasks.write_text("".join(f"{structures_dir() / r['folder']}\n"
                                     for r in todo))
            if not todo:
                print("nothing left to submit")
                return
        print(f"cleaned {cleaned} stage director(ies) of previous output")

    refstore = Path(__file__).resolve()
    # DFT is one array task per structure (each is hours of MPI).  MLIP is
    # chunked: loading the MatterSim model costs ~30 s, so a task that relaxed a
    # single small cell would spend most of its life in the import.
    if a.what == "mlip":
        n_tasks = -(-len(todo) // a.chunk)
    else:
        n_tasks = len(todo)          # after any post-clean shrink above
    cmd = ["sbatch",
           f"--array=0-{n_tasks - 1}%{a.throttle}",
           f"--chdir={root}",
           f"--output={jobs}/{a.what}-{tag}-%A_%a.out",
           f"--export=ALL,REFSTORE_TASKS={tasks},CSPFLOW_STORE={root},"
           f"REFSTORE={refstore},REFSTORE_CHUNK={a.chunk}",
           str(script)]
    print(" ".join(cmd))
    if not a.apply:
        print("\ndry run. add --apply to submit.")
        return
    done = subprocess.run(cmd, check=True, capture_output=True, text=True)
    print(done.stdout.strip())
    job_id = "".join(c for c in done.stdout if c.isdigit())
    if job_id:
        tasks.with_suffix(".tasks.jobid").write_text(job_id)



def folders_in_flight(root: Path) -> set[str]:
    """Structure folders already handed to a job that is still queued/running.

    Submitting one twice is not a nuisance, it is corruption: two VASP processes
    writing one directory.  Each submission records its job id beside its task
    file, so this only has to ask the scheduler which of those are still alive.
    """
    live: set[str] = set()
    for stamp in sorted((root / "jobs").glob("*.tasks.jobid")):
        job_id = stamp.read_text().strip()
        tasks = stamp.with_suffix("")                       # <name>.tasks
        if not job_id or not tasks.is_file():
            continue
        try:
            out = subprocess.run(
                ["squeue", "-h", "-j", job_id, "-t", "PD,R", "-o", "%i"],
                capture_output=True, text=True, timeout=30)
        except Exception:                                        # noqa: BLE001
            continue

        # Only tasks still PENDING or RUNNING hold their folder.  An array index
        # that already finished -- successfully or not -- will never run again,
        # so treating the whole task file as live would permanently block the
        # very structures that need a second attempt.
        indices: set[int] = set()
        for line in out.stdout.split():
            _, _, part = line.partition("_")
            part = part.strip("[]")
            for chunk in part.split(","):
                chunk = chunk.split("%")[0]
                if "-" in chunk:
                    lo, _, hi = chunk.partition("-")
                    if lo.isdigit() and hi.isdigit():
                        indices.update(range(int(lo), int(hi) + 1))
                elif chunk.isdigit():
                    indices.add(int(chunk))

        lines = [ln for ln in tasks.read_text().splitlines() if ln.strip()]
        live.update(Path(lines[i]).name for i in indices if i < len(lines))
    return live


