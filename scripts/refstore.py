DEFAULT_STORE = Path("/projects/mmi/cspflow-shared/store")

# Phases further above MP's own hull than this cannot change our hull, so we do
# not spend DFT on them.  One number, used everywhere.
DEFAULT_CUT = 0.5          # eV/atom

STAGES = ("relax", "static")
STAGE_DIR = {"relax": "dft_relax", "static": "dft_static"}


# --------------------------------------------------------------------------
# The store
# --------------------------------------------------------------------------

def store_root() -> Path:
    return Path(os.environ.get("CSPFLOW_STORE") or DEFAULT_STORE)


def structures_dir() -> Path:
    return store_root() / "structures"


def slug(mp_id: str, formula: str) -> str:
    """`mp-13` + `Fe` -> `mp-13-Fe`.  Reduced formulas are already path-safe."""
    return f"{mp_id}-{re.sub(r'[^A-Za-z0-9]', '', formula)}"


def mp_id_of(folder: Path) -> str:
    return folder.name.split("-", 2)[0] + "-" + folder.name.split("-", 2)[1]


def policy():
    """The ONE DFT policy, plus the machine.  Both from the store root."""
    import yaml

    from cspflow.cli import _dft_and_recipe
    from cspflow.config.schema import Machine

    root = store_root()
    settings = root / "settings.yaml"
    if not settings.is_file():
        sys.exit(f"no {settings}. The store needs exactly one DFT policy file.")
    dft, recipe, _ = _dft_and_recipe(settings, None)

    mfile = root / "machine.yaml"
    if not mfile.is_file():
        sys.exit(f"no {mfile}. The store needs exactly one machine profile.")
    machine = Machine(**yaml.safe_load(mfile.read_text()))
    return dft, recipe, machine


def read_atoms(path: Path):
    from ase.io import read
    return read(str(path))


def reduced_formula(atoms) -> str:
    from pymatgen.core import Composition
    return Composition(atoms.get_chemical_formula()).reduced_formula


def chemsys_of(atoms) -> str:
    return "-".join(sorted(set(atoms.get_chemical_symbols())))


# --------------------------------------------------------------------------
# migrate -- fold the old layouts into structures/
# --------------------------------------------------------------------------

OLD_SUBDIRS = {"relax": "dft_relax", "static": "dft_static", "mlip": "mlip",
               "dft_relax": "dft_relax", "dft_static": "dft_static"}
RUN_DIR = re.compile(r"^dft-(\d+)-(.+)$")


def _atoms_for(folder: Path):
    """Composition of an existing structure folder, from whatever it has."""
    for rel in ("relax/POSCAR", "dft_relax/POSCAR", "static/POSCAR",
                "mlip/CONTCAR", "relax/CONTCAR", "POSCAR.orig", "POSCAR"):
        p = folder / rel
        if p.is_file() and p.stat().st_size > 0:
            try:
                return read_atoms(p)
            except Exception:
                continue
    return None


def cmd_migrate(a) -> None:
    root = store_root()
    dest_root = structures_dir()
    moves: list[tuple[Path, Path]] = []
    problems: list[str] = []
    stats: Counter = Counter()

    # ---- source 1: the old `final/` tree, `final/mp-13/{relax,static,mlip}`
    final = root / "final"
    if final.is_dir():                       # the pre-reorganisation layout
        for d in sorted(final.iterdir()):
            if not d.is_dir() or not d.name.startswith("mp-"):
                continue
            atoms = _atoms_for(d)
            if atoms is None:
                stats["no_structure"] += 1
                problems.append(f"{d.name}: no readable POSCAR/CONTCAR anywhere")
                continue
            target = dest_root / slug(d.name, reduced_formula(atoms))
            for child in sorted(d.iterdir()):
                new = OLD_SUBDIRS.get(child.name, child.name)
                moves.append((child, target / new))
            stats["from_final"] += 1

    # ---- source 2: any campaign workdir, `<camp>/dft/dft-<row>-<stage>`
    # `archive/` is where migrated husks are parked; re-reading it would try to
    # migrate the same run directories a second time.
    for camp in sorted(root.iterdir()):
        if camp.name in ("archive", "structures", "mp-cache", "jobs", "logs"):
            continue
        dft = camp / "dft"
        db = camp / "campaign.db"
        if not (camp.is_dir() and dft.is_dir() and db.is_file()):
            continue
        from cspflow.db.store import Store
        with Store.open(db) as store:
            by_row = {int(r.id): str(r.key_value_pairs.get("mp_id") or "")
                      for r in store.structures()}
        for d in sorted(dft.iterdir()):
            if not d.is_dir():
                continue
            m = RUN_DIR.match(d.name)
            if not m:
                continue
            row, stage = int(m.group(1)), m.group(2)
            mp_id = by_row.get(row)
            if not mp_id:
                stats["no_mp_id"] += 1
                problems.append(f"{camp.name}/{d.name}: row {row} has no mp_id")
                continue
            atoms = _atoms_for(d)
            if atoms is None:
                stats["no_structure"] += 1
                problems.append(f"{camp.name}/{d.name}: no readable POSCAR")
                continue
            target = dest_root / slug(mp_id, reduced_formula(atoms))
            moves.append((d, target / STAGE_DIR.get(stage, stage)))
            stats[f"from_{camp.name}"] += 1

    print(f"store        {root}")
    print(f"destination  {dest_root}")
    for k, v in sorted(stats.items()):
        print(f"{k:<24} {v}")
    print(f"{'moves':<24} {len(moves)}")

    collisions = [(s, t) for s, t in moves if t.exists()]
    if collisions:
        print(f"{'already at destination':<24} {len(collisions)} (skipped)")
    for p in problems[:20]:
        print("  problem:", p)
    if len(problems) > 20:
        print(f"  ... and {len(problems) - 20} more")

    if not a.apply:
        print("\ndry run. add --apply to move.")
        return

    done = 0
    for src, tgt in moves:
        if tgt.exists() or not src.exists():
            continue
        tgt.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(src), str(tgt))
        done += 1
    print(f"moved {done}")

    # Remove the husks the moves left behind, but only if truly empty.
    for parent in {s.parent for s, _ in moves}:
        try:
            if parent.is_dir() and not any(parent.iterdir()):
                parent.rmdir()
        except OSError:
            pass


# --------------------------------------------------------------------------
# index -- rescan the tree, write index.csv.  Derived, so it cannot drift.
# --------------------------------------------------------------------------

COLUMNS = [
    "mp_id", "formula", "chemsys", "n_atoms", "folder",
    "mlip_state", "e_mlip_relaxed",
    "relax_state", "relax_converged", "relax_core_hours",
    "static_state", "e_static_eV", "e_per_atom_eV", "magnetization_uB",
    "ready", "fail_reason",
]


def scan_one(folder: Path) -> dict:
    from cspflow.dft.vasp.parse import read_job_directory

    row = {c: "" for c in COLUMNS}
    row["folder"] = folder.name
    parts = folder.name.split("-")
    row["mp_id"] = "-".join(parts[:2])
    row["formula"] = "-".join(parts[2:])

    info = folder / "info.json"
    if info.is_file():
        try:
            d = json.loads(info.read_text())
            row["chemsys"] = d.get("chemsys", "")
            row["formula"] = d.get("formula", row["formula"])
        except Exception:
            pass

    mlip = folder / "mlip" / "mlip.json"
    if mlip.is_file():
        try:
            d = json.loads(mlip.read_text())
            row["mlip_state"] = "done" if d.get("converged", True) else "unconverged"
            row["e_mlip_relaxed"] = d.get("e_mlip_relaxed", d.get("energy", ""))
        except Exception:
            row["mlip_state"] = "unreadable"
    elif (folder / "mlip").is_dir():
        row["mlip_state"] = "partial"
    else:
        row["mlip_state"] = "todo"

    fails = []
    for stage in STAGES:
        d = folder / STAGE_DIR[stage]
        if not d.is_dir():
            row[f"{stage}_state"] = "todo"
            continue
        if not (d / "OUTCAR").is_file() and not (d / "INCAR").is_file():
            row[f"{stage}_state"] = "todo"
            continue
        out = read_job_directory(d)
        row[f"{stage}_state"] = out.state
        if out.exit_reason:
            fails.append(f"{stage}: {out.exit_reason}")
        if stage == "relax":
            row["relax_converged"] = out.converged
            row["relax_core_hours"] = round(out.core_hours, 2)
            if not row["chemsys"] and out.potcar_symbols:
                row["chemsys"] = "-".join(sorted({s.split("_")[0]
                                                  for s in out.potcar_symbols}))
        else:
            row["n_atoms"] = out.n_atoms or ""
            row["e_static_eV"] = out.energy if out.energy is not None else ""
            row["e_per_atom_eV"] = (round(out.e_per_atom, 6)
                                    if out.e_per_atom is not None else "")
            row["magnetization_uB"] = (out.magnetisation
                                       if out.magnetisation is not None else "")

    # A folder that has not been run yet has no OUTCAR and no POTCAR to read the
    # chemistry from, so fall back to whatever geometry it does have.  Without
    # this, `status Ce-Fe-B` silently omits everything still to do.
    if not row["chemsys"] or not row["n_atoms"]:
        atoms = _atoms_for(folder)
        if atoms is not None:
            row["chemsys"] = row["chemsys"] or chemsys_of(atoms)
            row["n_atoms"] = row["n_atoms"] or len(atoms)
            if not row["formula"] or row["formula"] == "-".join(parts[2:]):
                row["formula"] = reduced_formula(atoms)

    # Backfilling n_atoms above is not enough on its own: e_per_atom was derived
    # EARLIER, from the OUTCAR's own n_atoms, and a row that needed the backfill
    # therefore carries a total energy with no per-atom energy. It then looks
    # complete -- static_state done, ready True -- while being invisible to any
    # hull built on e_per_atom_eV. Derive it here, once n_atoms is known.
    # (2026-09-15: 65 rows were in this state, including mp-4459 Ce2Fe14B.)
    if (not row["e_per_atom_eV"]) and row["e_static_eV"] and row["n_atoms"]:
        try:
            row["e_per_atom_eV"] = round(float(row["e_static_eV"]) / int(row["n_atoms"]), 6)
        except (TypeError, ValueError, ZeroDivisionError):
            pass

    row["fail_reason"] = "; ".join(fails)
    # `ready` is the only column the hull builder looks at: a static energy that
    # came after a relax that actually converged.
    row["ready"] = bool(row["e_static_eV"] != "" and row["relax_converged"] is True
                        and row["static_state"] == "done")
    return row


def cmd_index(a) -> None:
    root = store_root()
    folders = sorted(p for p in structures_dir().glob("mp-*") if p.is_dir())
    # Every scan is a handful of small NFS reads, so this is latency-bound, not
    # CPU-bound: threads turn a 10-minute serial walk into well under a minute.
    from concurrent.futures import ThreadPoolExecutor
    rows = []
    with ThreadPoolExecutor(max_workers=a.workers) as pool:
        for i, row in enumerate(pool.map(scan_one, folders), 1):
            rows.append(row)
            if i % 500 == 0:
                print(f"  scanned {i}/{len(folders)}", flush=True)
    rows.sort(key=lambda r: r["folder"])

    csv_path = root / "index.csv"
    with csv_path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    (root / "index.json").write_text(json.dumps(rows, indent=1, default=str))

    ready = sum(1 for r in rows if r["ready"])
    print(f"{len(rows)} structures -> {csv_path}")
    print(f"  hull-ready       {ready}")
    for stage in STAGES:
        c = Counter(r[f"{stage}_state"] for r in rows)
        print(f"  {stage:<8} " + "  ".join(f"{k}={v}" for k, v in sorted(c.items())))
    c = Counter(r["mlip_state"] for r in rows)
    print("  mlip     " + "  ".join(f"{k}={v}" for k, v in sorted(c.items())))


def load_index() -> list[dict]:
    p = store_root() / "index.csv"
    if not p.is_file():
        sys.exit(f"no {p}. Run: refstore.py index")
    with p.open() as fh:
        return list(csv.DictReader(fh))


# --------------------------------------------------------------------------
# refresh -- rewrite the inputs of every unfinished stage, keeping progress
# --------------------------------------------------------------------------

def refresh_folder(folder: Path, *, ntasks: int | None = None,
                   apply: bool = False) -> dict:
    """Put one unfinished structure back in a runnable, correctly-parallel state.

    Three things happen, in this order, and the order is the whole point:

      1. the geometry the last attempt actually REACHED is preserved
         (dft_relax/CONTCAR), so a killed relax continues rather than
         restarting from the MP cell;
      2. the residue of that attempt is removed, because a half-written OUTCAR
         beside a live one is unreadable and a stale CHGCAR can poison the run
         it is meant to help;
      3. the inputs are rewritten WITH the rank count, which is what turns the
         KPAR/NCORE planner on.  Folders written before 2026-09-10 have no
         KPAR at all -- see docs/10-reference-set.md.

    The relax k-grid is re-derived from the restart cell.  That is safe: it is
    a reciprocal DENSITY, so the grid barely moves, and the energy that reaches
    the hull comes from the static, whose grid is re-derived from the relaxed
    cell either way.  The relax grid only affects the path.
    """
    rec = {"folder": folder.name, "action": "-", "kpar_before": None,
           "kpar_after": None, "cleaned": "-", "geometry": "-"}
    relax = folder / "dft_relax"
    inc = relax / "INCAR"
    if inc.is_file():
        rec["kpar_before"] = "KPAR" in inc.read_text()

    # Where to restart from, best first.  CONTCAR is the cell the last attempt
    # reached.  If there is none but a POSCAR is present, that POSCAR IS the
    # reached cell -- a previous refresh already carried it there and removed
    # the CONTCAR -- so it must be preferred over the seed chain.  Without this
    # branch a second refresh silently throws the first one's progress away and
    # restarts from the MLIP cell; measured on mp-1056831-O2, 2026-09-10.
    contcar = relax / "CONTCAR"
    poscar = relax / "POSCAR"
    if contcar.is_file() and contcar.stat().st_size > 0:
        restart_from, rec["geometry"] = contcar, "CONTCAR (continue)"
    elif poscar.is_file() and poscar.stat().st_size > 0:
        restart_from, rec["geometry"] = poscar, "POSCAR (continue)"
    else:
        restart_from, rec["geometry"] = None, "seed (restart)"
    resume = restart_from is not None

    if not apply:
        rec["action"] = "would refresh"
        return rec

    # 1. keep the reached geometry out of clean_stage's way
    keep = relax / "POSCAR.restart"
    if resume:
        shutil.copyfile(restart_from, keep)

    # 2. remove the previous attempt
    # clean_stage returns the REASON string it logged, not a count.
    rec["cleaned"] = clean_stage(relax, carry_contcar=False) or "-"
    clean_stage(folder / "dft_static", carry_contcar=False)

    # 3. rewrite the inputs with the planner on
    try:
        # `folder`, NOT `relax`: write_stage_inputs appends STAGE_DIR itself,
        # so handing it the stage directory writes dft_relax/dft_relax and
        # leaves the real INCAR untouched.  Caught by a two-folder test.
        write_stage_inputs(folder, "relax", ntasks=ntasks,
                           geometry=keep if resume else None)
    finally:
        keep.unlink(missing_ok=True)

    rec["kpar_after"] = "KPAR" in inc.read_text() if inc.is_file() else False
    rec["action"] = "refreshed"
    return rec


def cmd_refresh(a) -> None:
    root = store_root()
    rows = [r for r in load_index() if r["ready"] != "True"]
    if a.folder:
        rows = [r for r in rows if r["folder"] in set(a.folder)]
    if a.chemsys:
        want = set(a.chemsys.split("-"))
        rows = [r for r in rows
                if r["chemsys"] and set(r["chemsys"].split("-")) <= want]

    ignored = load_ignored()
    skipped_ignored = [r for r in todo if r["mp_id"] in ignored]
    if skipped_ignored:
        todo = [r for r in todo if r["mp_id"] not in ignored]
        print(f"skipping {len(skipped_ignored)} structure(s) listed in "
              f"ignored.json -- too far above the hull to matter, not failures")

    held = folders_in_flight(root)
    skipped = [r for r in rows if r["folder"] in held]
    rows = [r for r in rows if r["folder"] not in held]
    if skipped:
        print(f"skipping {len(skipped)} folder(s) held by a live task -- "
              f"refreshing one under a running VASP would corrupt it")
    if a.limit:
        rows = rows[: a.limit]

    n = job_ntasks(a.ntasks)
    print(f"{len(rows)} folder(s) to refresh, planning for {n} ranks")
    recs = []
    for r in rows:
        rec = refresh_folder(structures_dir() / r["folder"], ntasks=n, apply=a.apply)
        recs.append(rec)
        if a.verbose or len(rows) <= 20:
            print(f"  {rec['folder']:<26} {rec['geometry']:<20} "
                  f"KPAR {rec['kpar_before']} -> {rec['kpar_after']}  "
                  f"{str(rec['cleaned'])[:52]}")
    gained = sum(1 for r in recs if r["kpar_before"] is False and r["kpar_after"])
    cont = sum(1 for r in recs if r["geometry"].startswith("CONTCAR"))
    print(f"  continued from CONTCAR        {cont}")
    print(f"  restarted from the seed       {len(recs) - cont}")
    if a.apply:
        print(f"  gained KPAR (had none)        {gained}")
    else:
        print("\ndry run. add --apply to rewrite.")


