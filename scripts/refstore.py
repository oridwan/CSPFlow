def sbatch_ntasks(script: str = "refstore_dft.sbatch") -> int | None:
    """The rank count the DFT job itself declares, read from its #SBATCH line.

    This is the authority, not the environment.  See job_ntasks().
    """
    f = Path(__file__).with_name(script)
    try:
        for line in f.read_text().splitlines():
            if line.startswith("#SBATCH") and "--ntasks=" in line:
                return int(line.split("--ntasks=")[1].split()[0])
    except (OSError, ValueError, IndexError):
        pass
    return None


def job_ntasks(explicit: int | None = None) -> int:
    """How many MPI ranks the VASP job will have.

    This is NOT cosmetic.  `resolve_inputs` only runs its parallel planner when
    it is told the rank count -- `if ntasks:` -- so leaving it None silently
    ships every INCAR with KPAR unset, i.e. KPAR=1, i.e. VASP walking the
    k-points one after another with no k-point parallelism at all.  Measured
    2026-09-10 on the iron-oxide tail of this store, that cost 4x to 8x on the
    ten slowest running jobs.  See docs/10-reference-set.md.

    $SLURM_NTASKS is trusted ONLY when this process is actually inside the DFT
    array task.  A login shell can be inside an allocation of its own: this
    cluster's Open OnDemand dashboard runs with SLURM_NTASKS=2, so a hand-run
    `inputs` or `refresh` from such a shell would otherwise plan a 32-rank job
    for 2 ranks and write a KPAR that does not divide the real rank count --
    which VASP rejects at startup.  Found the hard way, 2026-09-10.

    Order: an explicit --ntasks; else SLURM's value if we are in a ref-dft
    task; else what refstore_dft.sbatch itself asks for; else the machine
    profile default.
    """
    if explicit:
        return int(explicit)
    if os.environ.get("SLURM_JOB_NAME", "").startswith("ref-"):
        for var in ("SLURM_NTASKS", "SLURM_NPROCS"):
            val = os.environ.get(var)
            if val and val.isdigit() and int(val) > 0:
                return int(val)
    from_script = sbatch_ntasks()
    if from_script:
        return from_script
    try:
        _, _, machine = policy()
        return int(getattr(machine.defaults, "ntasks", 0)) or 32
    except Exception:
        return 32


def write_stage_inputs(folder: Path, stage: str, ntasks: int | None = None,
                       geometry: Path | None = None) -> Path:
    """Write INCAR/KPOINTS/POSCAR/POTCAR for `stage` into `folder`.

    The geometry comes from the best available source, in this order:
        static : dft_relax/CONTCAR   (the relaxed cell -- this is the carry)
        relax  : mlip/CONTCAR, else the MP structure in POSCAR.orig
    """
    from cspflow.dft.vasp.inputs import resolve_inputs, write_inputs

    dft, recipe, machine = policy()
    st = {s.name: s for s in recipe.stages}[stage]
    out = folder / STAGE_DIR[stage]

    if geometry is not None:
        # An explicit restart geometry.  `refresh` uses this to rewrite an
        # INCAR from the cell a killed relax had already reached, instead of
        # throwing that progress away and starting from the seed again.
        src = Path(geometry)
        if not src.is_file() or not src.stat().st_size:
            raise SystemExit(f"{folder.name}: --geometry {src} is missing or empty")
    elif stage == "static":
        src = folder / "dft_relax" / "CONTCAR"
        if not src.is_file() or src.stat().st_size == 0:
            raise SystemExit(f"{folder.name}: no relaxed CONTCAR to carry into static")
    else:
        # `dft_relax/POSCAR` is the ORIGINAL input geometry -- VASP never
        # overwrites it (it writes CONTCAR instead) -- so it is the right seed
        # for a folder migrated from the old layout, which has no POSCAR.orig.
        for cand in ("mlip/CONTCAR", "POSCAR.orig", "dft_relax/POSCAR"):
            src = folder / cand
            if src.is_file() and src.stat().st_size:
                break
        else:
            raise SystemExit(f"{folder.name}: no starting geometry")

    atoms = read_atoms(src)
    # ntasks is what turns the KPAR/NCORE planner on -- see job_ntasks().
    resolved = resolve_inputs(atoms, st, dft, machine, ntasks=job_ntasks(ntasks))
    out.mkdir(parents=True, exist_ok=True)
    write_inputs(resolved, resolved.atoms if resolved.atoms is not None else atoms, out)
    return out


def cmd_inputs(a) -> None:
    folder = Path(a.dir)
    if not folder.is_absolute():
        folder = structures_dir() / folder
    out = write_stage_inputs(folder, a.stage, ntasks=getattr(a, "ntasks", None),
                             geometry=Path(a.geometry) if getattr(a, "geometry", None) else None)
    tags = {}
    for line in (out / "INCAR").read_text().splitlines():
        k, _, v = line.partition("=")
        if v:
            tags[k.strip()] = v.split("#")[0].strip()
    print(f"{out}  KPAR={tags.get('KPAR', 'unset')} "
          f"NCORE={tags.get('NCORE', 'unset')} ntasks={job_ntasks(getattr(a, 'ntasks', None))}")


