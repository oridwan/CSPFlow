def cmd_add(a) -> None:
    from cspflow.reference.mp import fetch_chemsys, fetch_structures

    root = store_root()
    cache = root / "mp-cache"
    cache.mkdir(parents=True, exist_ok=True)
    have = {p.name.split("-")[0] + "-" + p.name.split("-")[1]
            for p in structures_dir().glob("mp-*") if p.is_dir()}

    created, skipped_have, skipped_far = 0, 0, 0
    for chemsys in a.chemsys:
        res = fetch_chemsys(chemsys, cache=cache)
        structs = fetch_structures(chemsys, cache=cache)
        print(f"{chemsys}: {len(res.entries)} MP entries "
              f"(includes every sub-system)")
        for e in res.entries:
            if e.mp_id in have:
                skipped_have += 1
                continue
            # `e_above_hull_mp`, not `e_above_hull`.  The attribute was
            # misnamed here, so `above` was ALWAYS None: --cut never fired and
            # every info.json recorded a null distance.  Found 2026-09-11.
            above = getattr(e, "e_above_hull_mp", None)
            if a.cut and above is not None and above > a.cut:
                skipped_far += 1
                continue
            s = structs.get(e.mp_id)
            if s is None:
                continue
            folder = structures_dir() / slug(e.mp_id, s.composition.reduced_formula)
            created += 1
            if not a.apply:
                continue
            folder.mkdir(parents=True, exist_ok=True)
            from pymatgen.io.vasp.inputs import Poscar
            Poscar(s).write_file(str(folder / "POSCAR.orig"))
            (folder / "info.json").write_text(json.dumps({
                "mp_id": e.mp_id,
                "formula": s.composition.reduced_formula,
                "chemsys": "-".join(sorted({str(x) for x in s.composition.elements})),
                "n_atoms": len(s),
                "source": "materials-project",
                "e_above_hull_mp": above,
                "requested_for": chemsys,
            }, indent=2))

    print(f"\nalready in the store   {skipped_have}")
    print(f"above the {a.cut} eV/atom cut  {skipped_far}")
    print(f"to create              {created}")
    if not a.apply:
        print("\ndry run. add --apply to create the folders.")



# Files VASP writes.  Everything else in a stage directory is an input we keep.
VASP_OUTPUTS = ("OUTCAR", "OSZICAR", "vasprun.xml", "CONTCAR", "CHG", "CHGCAR",
                "WAVECAR", "EIGENVAL", "DOSCAR", "PROCAR", "PCDAT", "XDATCAR",
                "REPORT", "IBZKPT", "vasp.out", "VASP_DONE", "POSCAR.prev",
                "vaspout.h5", "ML_LOGFILE")

FAILURE_HINT = re.compile(
    r"(ZBRENT[^|\n]{0,40}|VERY BAD NEWS[^|\n]{0,60}|illegal instruction"
    r"|reached required accuracy)")


def clean_stage(stage_dir: Path, *, carry_contcar: bool) -> str:
    """Delete a dead attempt's output, keeping one line saying what it was.

    Two reasons this is not optional.  A rerun that leaves the old files in
    place gives you a directory holding half of a dead run and half of a live
    one the moment the new attempt crashes early -- and `refcheck.py`, reading
    the stale OUTCAR, keeps reporting a failure that was already fixed.  A
    leftover CHGCAR or WAVECAR from a crashed run can also poison the restart
    it is supposed to accelerate.

    `carry_contcar` is for the relax: the geometry the dead attempt reached is
    the one thing worth keeping, so it becomes the new POSCAR *before* the
    delete, not after.
    """
    if not stage_dir.is_dir():
        return ""

    reason = ""
    for name in ("OUTCAR", "vasp.out"):
        f = stage_dir / name
        if f.is_file() and f.stat().st_size:
            m = FAILURE_HINT.search(tail_text(f))
            if m:
                reason = m.group(1).strip()
                break

    contcar = stage_dir / "CONTCAR"
    if carry_contcar and contcar.is_file() and contcar.stat().st_size:
        (stage_dir / "POSCAR").write_bytes(contcar.read_bytes())
        reason = (reason + "; " if reason else "") + "geometry carried to POSCAR"

    removed = 0
    for name in VASP_OUTPUTS:
        f = stage_dir / name
        if f.is_file():
            f.unlink()
            removed += 1
    if removed:
        with (stage_dir / "RETRY.log").open("a") as fh:
            fh.write(f"{time.strftime('%Y-%m-%dT%H:%M:%S')}  cleaned {removed} "
                     f"file(s) from the previous attempt"
                     f"{' -- ' + reason if reason else ''}\n")
    return reason


