#!/usr/bin/env python
"""
refstore.py -- the reference set as ONE folder, not a campaign.

WHAT THIS IS
    The reference set is a global asset: a list of known Materials Project
    phases, each recomputed with OUR DFT settings, used to build convex hulls
    for any campaign.  It is NOT a campaign.  It has no generation, no
    screening, no calibration -- just two VASP runs per structure.

    Before this script it was spread over three places (an MP cache, a `final/`
    tree, and a live campaign workdir whose folders were named `dft-110-relax`),
    and results only reached `final/` when someone ran a separate collect step.
    This script replaces all of that with one folder and one CSV.

LAYOUT (everything lives under $CSPFLOW_STORE, default /projects/mmi/cspflow-shared/store)

    settings.yaml            the ONE DFT policy.  Never overridden per-run.
    machine.yaml             the ONE machine profile (partitions, POTCAR paths).
    index.csv                THE bookkeeping file.  Regenerated by `index`.
    index.json               same content, for scripts.
    mp-cache/                MP downloads (json), shared across campaigns.
    jobs/                    task lists + slurm logs.
    structures/
        mp-13-Fe/            <-- MP id AND composition, so the tree is greppable
            info.json        what this phase is + where it came from
            mlip/            MatterSim relax (GPU job)     CONTCAR relaxed.cif mlip.json
            dft_relax/       VASP relax   \  ONE CPU job: relax -> CONTCAR becomes
            dft_static/      VASP static  /  static POSCAR -> static

WHY THE COMPOSITION IS IN THE FOLDER NAME
    So `ls structures | grep Ce` answers "what Ce phases do I have" without
    opening a database.

THE ONE RULE THAT CANNOT BE RELAXED
    Every energy on one hull must come from the same DFT policy.  Mixing
    policies shifted our energies by +0.19 eV/atom against MP, while the
    selection threshold is 0.06 eV/atom.  So settings.yaml is read from the
    store root and nothing overrides it.  You never type a recipe id.

INPUTS
    $CSPFLOW_STORE/settings.yaml, machine.yaml   (policy, required)
    $MP_API_KEY                                  (only for `add`, never written down)
    Materials Project                            (only for `add`, then cached)

OUTPUTS
    $CSPFLOW_STORE/structures/<mp-id>-<formula>/...
    $CSPFLOW_STORE/index.csv, index.json
    $CSPFLOW_STORE/jobs/<name>.tasks             one folder path per line

COMMANDS
    refstore.py migrate  [--apply]            fold old layouts into structures/
    refstore.py add      CHEMSYS... [--apply] fetch MP, add what is missing
    refstore.py inputs   DIR --stage relax|static     write VASP input files
    refstore.py index                         rescan the tree -> index.csv
    refstore.py status   [CHEMSYS]            human summary
    refstore.py submit   mlip|dft [--limit N] [--apply]   task list + sbatch
    refstore.py hull     CHEMSYS              build the hull from index.csv

RUN
    export CSPFLOW_STORE=/projects/mmi/cspflow-shared/store
    python scripts/refstore.py status
"""

