def load_ignored() -> dict[str, dict]:
    """mp_id -> record, from <store>/ignored.json.

    IGNORED is not FAILED.  These structures compute fine; they just sit too
    far above the convex hull to be able to change it, so the store does not
    wait for them.  Kept as a file rather than a rule so the decision is
    reviewable and reversible: delete an entry and it comes back.

    Distinct from excluded.json, which holds structures that CANNOT be
    computed as given (vacuum clusters, 0.80 A contacts).  Those are failures.
    """
    f = store_root() / "ignored.json"
    try:
        return json.loads(f.read_text()).get("ignored", {})
    except (OSError, ValueError):
        return {}


def mp_hull_distance() -> dict[str, float]:
    """mp_id -> MP's own e_above_hull, read from the store's fetch cache.

    Used only to decide whether a MISSING structure can matter. A phase far
    above the hull cannot be on it, so waiting for it is waiting for nothing.
    The number is MP's, computed at MP's settings -- but e_above_hull is a
    distance WITHIN a chemical system, so the systematic ours-minus-MP offset
    (measured 0.15-0.21 eV/atom on this store) largely cancels. It is a
    triage number, never an energy that reaches a hull.
    """
    out: dict[str, float] = {}
    for f in (store_root() / "mp-cache").glob("*__GGA_GGApU.json"):
        try:
            data = json.loads(f.read_text())
        except (OSError, ValueError):
            continue
        for e in data.get("entries", []):
            mid, eah = e.get("mp_id"), e.get("e_above_hull_mp")
            if mid is not None and eah is not None:
                out[mid] = min(out.get(mid, float("inf")), float(eah))
    return out


def cmd_hull(a) -> None:
    """Build a hull from the store FOLDER, on one of its three energy scales.

    No export step and no recipe_id: the store is the source of truth and the
    entries are read out of it. See cspflow/reference/refstore.py.
    """
    from cspflow.reference.hull import build_hull
    from cspflow.reference.refstore import (ENERGY_SOURCES, StoreError,
                                            coverage, entries_for, stale_minutes)

    age = stale_minutes()
    if age > 10:
        print(f"note: index.csv is {age:.0f} minutes old -- `refstore.py index` "
              f"first if a batch has finished since.")

    sources = list(ENERGY_SOURCES) if a.compare else [a.energy]
    for src in sources:
        cov = coverage(a.chemsys, src)
        far = mp_hull_distance()
        blocking = [m for m in cov.missing if far.get(m, float("inf")) <= a.ignore_above]
        waivable = [m for m in cov.missing if m not in blocking]

        head = f"{a.chemsys} [{src}]"
        print(f"\n{head}: {len(cov.have)} usable, {len(cov.missing)} without an energy")
        if cov.ignored:
            print(f"  {len(cov.ignored)} in ignored.json (too far above the hull to matter)")
        if waivable:
            # unfinished, but MP puts them far enough above the hull that they
            # cannot be vertices -- refusing over these blocks a campaign for
            # nothing. Named anyway: a phase silently dropped is how a hull
            # quietly becomes wrong.
            print(f"  {len(waivable)} unfinished but > {a.ignore_above} eV/atom above "
                  f"MP's hull -- ignored:")
            for m in waivable[:8]:
                print(f"    {m:<18} MP e_above_hull {far.get(m, float('nan')):.3f}")
        if blocking:
            print(f"  {len(blocking)} unfinished and CLOSE ENOUGH to matter "
                  f"(<= {a.ignore_above} eV/atom):")
            for m in blocking:
                d = far.get(m, float("inf"))
                tag = "ON THE HULL" if d <= 0.001 else f"e_above_hull {d:.3f}"
                print(f"    {m:<18} {tag}")
            print("\nA hull built without these is not the hull. Finish them first:")
            print(f"  python {Path(__file__).name} submit dft --chemsys {a.chemsys} --apply")
            continue
        try:
            entries = entries_for(a.chemsys, src, allow_partial=True)
        except StoreError as exc:
            print(f"  {exc}")
            continue
        print(build_hull(entries).render())


