def cmd_status(a) -> None:
    rows = load_index()
    ignored = load_ignored()
    # store_root(), not a bare `root` -- that name is local to cmd_submit,
    # where this stale-index warning was written first.
    age = (time.time() - (store_root() / "index.csv").stat().st_mtime) / 60
    if age > 10:
        print(f"note: index.csv is {age:.0f} minutes old. Every folder is "
              f"re-read before anything is deleted, so this is safe -- but "
              f"`refstore.py index` first gives a truer task list.")
    if a.chemsys:
        want = set(a.chemsys.split("-"))
        rows = [r for r in rows
                if r["chemsys"] and set(r["chemsys"].split("-")) <= want]
        print(f"chemsys {a.chemsys}: {len(rows)} phases in the store "
              f"(including every sub-system)")
    ready = [r for r in rows if r["ready"] == "True"]
    todo = [r for r in rows if r["ready"] != "True"]
    # IGNORED is a third state, not a kind of failure.  Counting these as
    # outstanding work made the store look 67 structures further from done
    # than it is, and invited exactly the wasted effort this file prevents.
    skip = [r for r in todo if r["mp_id"] in ignored]
    todo = [r for r in todo if r["mp_id"] not in ignored]
    print(f"total            {len(rows)}")
    print(f"hull-ready       {len(ready)}")
    if skip:
        print(f"ignored          {len(skip)}   (too far above the hull to "
              f"matter -- see ignored.json; NOT failures)")
    print(f"outstanding      {len(todo)}")
    c = Counter(r["fail_reason"] or f"{r['relax_state']}/{r['static_state']}"
                for r in todo)
    for k, v in c.most_common(12):
        print(f"  {v:>5}  {k}")


