# Largest lattice parameter accepted for a STORE structure, in Angstrom.  The
# store is MP-derived; the longest axis it holds after Niggli reduction is
# ~65 A (mp-684606, Cu27Se20).  120 leaves headroom without admitting a cell
# whose axis is longer than any real crystal in the set.
STORE_MAX_LATTICE_A = 120.0


def relax_one_mlip(folder: Path, engine) -> dict:
    """Relax one structure with the MLIP and write `mlip/` beside the DFT dirs.

    The relaxed cell is the useful product: it is a far better starting point
    for the DFT relax than MP's own geometry, and it used to be thrown away.
    """
    from ase.io import write as ase_write

    for cand in ("POSCAR.orig", "dft_relax/POSCAR"):
        seed = folder / cand
        if seed.is_file() and seed.stat().st_size:
            break
    else:
        return {"folder": folder.name, "ok": False, "error": "no seed geometry"}

    atoms = read_atoms(seed)
    res = engine.relax(atoms)
    out = folder / "mlip"
    out.mkdir(parents=True, exist_ok=True)
    rec = {
        "mp_id": "-".join(folder.name.split("-")[:2]),
        "formula": atoms.get_chemical_formula(),
        "converged": bool(res.converged),
        "e_mlip_relaxed": res.energy,
        "e_per_atom": res.e_per_atom,
        "mlip_fmax": res.fmax,
        "mlip_steps": res.n_steps,
        "model": getattr(engine, "model", ""),
        "volume_initial": float(atoms.get_volume()),
    }
    if res.atoms is not None:
        ase_write(str(out / "CONTCAR"), res.atoms, format="vasp", direct=True)
        ase_write(str(out / "relaxed.cif"), res.atoms)
        rec["volume_final"] = float(res.atoms.get_volume())
    (out / "mlip.json").write_text(json.dumps(rec, indent=2, sort_keys=True))
    return {"folder": folder.name, "ok": res.energy is not None, **rec}


def cmd_mlip(a) -> None:
    from cspflow.mlip import MatterSimEngine, apply_ase_compat_shim

    apply_ase_compat_shim()
    if a.tasks:
        folders = [Path(line) for line in
                   Path(a.tasks).read_text().split() if line.strip()]
    else:
        folders = [structures_dir() / d if not Path(d).is_absolute() else Path(d)
                   for d in a.dirs]
    if a.start or a.count:
        folders = folders[a.start: a.start + a.count if a.count else None]

    # The store's structures come from Materials Project, so a long axis is a
    # real long-period polytype (Cu27Se20 is c = 65 A) rather than the generated
    # nonsense the 50 A default guards against.  Raising the cap here does not
    # touch campaign screening, which keeps the default.
    engine = MatterSimEngine(max_lattice=STORE_MAX_LATTICE_A)
    ok = bad = 0
    for i, f in enumerate(folders, 1):
        try:
            r = relax_one_mlip(f, engine)
            ok += bool(r.get("ok"))
            bad += not r.get("ok")
            print(f"[{i}/{len(folders)}] {f.name:<28} "
                  f"E={r.get('e_mlip_relaxed')} fmax={r.get('mlip_fmax')}", flush=True)
        except Exception as exc:                                    # noqa: BLE001
            bad += 1
            print(f"[{i}/{len(folders)}] {f.name:<28} FAILED: {exc}", flush=True)
    print(f"done: {ok} ok, {bad} failed")


